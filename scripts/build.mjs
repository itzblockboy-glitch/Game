/**
 * Production build: esbuild bundles src/main.js (single ES module) and the CSS,
 * emits dist/, and copies only the assets the runtime actually requests.
 * Result: ~6 requests for the shell + a handful of GLBs, all brotli/gzip-able.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as esbuild from 'esbuild';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const DIST = path.join(ROOT, 'dist');

fs.rmSync(DIST, { recursive: true, force: true });
fs.mkdirSync(path.join(DIST, 'models'), { recursive: true });
fs.mkdirSync(path.join(DIST, 'draco'), { recursive: true });

// The inline boot guard must exist as a real file in dist/ before index.html
// references it — a 404 here is one of the ways the page can come up empty.
fs.copyFileSync(path.join(ROOT, 'src/boot-guard.js'), path.join(DIST, 'boot-guard.js'));

const result = await esbuild.build({
  entryPoints: [path.join(ROOT, 'src/main.js')],
  bundle: true,
  format: 'esm',
  // es2019 (not es2020): optional chaining / nullish coalescing were introduced
  // in Chromium 80. Down-levelling them means the bundle still *parses* on much
  // older Android WebViews, instead of dying as a SyntaxError with a black page.
  target: 'es2019',
  minify: true,
  sourcemap: false,
  legalComments: 'none',
  outfile: path.join(DIST, 'app.js'),
  metafile: true,
  alias: { three: path.join(ROOT, 'src/vendor/three.module.js') },
  logLevel: 'warning',
  alias: { three: path.join(ROOT, 'src/vendor/three.module.js') },
});

await esbuild.build({
  entryPoints: [path.join(ROOT, 'src/styles.css')],
  bundle: true,
  minify: true,
  outfile: path.join(DIST, 'styles.css'),
  logLevel: 'warning',
});

// index.html (rewritten to the bundle)
let html = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');
html = html
  .replace('/src/styles.css', '/styles.css')
  .replace('<script type="module" src="/src/main.js"></script>', '<script type="module" src="/app.js"></script>');
fs.writeFileSync(path.join(DIST, 'index.html'), html);
fs.copyFileSync(path.join(ROOT, 'public/manifest.webmanifest'), path.join(DIST, 'manifest.webmanifest'));

// models + manifest + colliders (generated by npm run assets)
const MODELS = path.join(ROOT, 'public/models');
for (const f of fs.readdirSync(MODELS)) {
  if (!f.endsWith('.glb') && !f.endsWith('.json')) continue;
  fs.copyFileSync(path.join(MODELS, f), path.join(DIST, 'models', f));
}
// draco decoders
for (const f of fs.readdirSync(path.join(ROOT, 'public/draco'))) {
  fs.copyFileSync(path.join(ROOT, 'public/draco', f), path.join(DIST, 'draco', f));
}
// icons (PWA + launcher)
const ICONS = path.join(ROOT, 'public/icons');
if (fs.existsSync(ICONS)) {
  fs.mkdirSync(path.join(DIST, 'icons'), { recursive: true });
  for (const f of fs.readdirSync(ICONS)) {
    fs.copyFileSync(path.join(ICONS, f), path.join(DIST, 'icons', f));
  }
}
// favicon / misc public files (if any)
for (const f of fs.readdirSync(path.join(ROOT, 'public'))) {
  const p = path.join(ROOT, 'public', f);
  if (fs.statSync(p).isFile() && !f.endsWith('.webmanifest')) fs.copyFileSync(p, path.join(DIST, f));
}

const totalSize = (dir) =>
  fs.readdirSync(dir, { withFileTypes: true }).reduce((a, e) => {
    const p = path.join(dir, e.name);
    return a + (e.isDirectory() ? totalSize(p) : fs.statSync(p).size);
  }, 0);

console.log(`  build: dist/ (${(totalSize(DIST) / 1024 / 1024).toFixed(2)} MB) · app.js ${(
  fs.statSync(path.join(DIST, 'app.js')).size / 1024
).toFixed(0)} KB · ${Object.keys(result.metafile.inputs).length} modules`);
